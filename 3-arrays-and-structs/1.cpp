#include <iostream>

int main()
{
    size_t n = 0;
    std::cin >> n;

    // Массив хранит все введённые числа, чтобы к ним можно было обратиться
    // в обратном порядке после завершения чтения.
    int arr[1000];

    // Заполняем первые n ячеек массива.
    for (size_t i = 0; i < n; ++i)
    {
        std::cin >> arr[i];
    }

    // При i = 0 берём последний элемент, затем сдвигаемся к началу массива.
    for (size_t i = 0; i < n; ++i)
    {
        std::cout << arr[n - i - 1] << " ";
    }
}
