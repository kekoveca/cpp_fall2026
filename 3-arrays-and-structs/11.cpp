#include <iostream>

int main()
{
    int n, m;
    std::cin >> n >> m;

    // Храним символы исходного прямоугольника вместе с пробелами.
    char arr[25][25];

    // После чтения размеров убираем перевод строки перед первым рядом.
    std::cin.ignore();

    // get считывает каждый символ, включая пробелы внутри ряда.
    for (int i = 0; i < n; ++i)
    {
        for (int j = 0; j < m; ++j)
        {
            std::cin.get(arr[i][j]);
        }

        // Между рядами пропускаем разделяющий перевод строки.
        if (i < n - 1)
        {
            std::cin.ignore();
        }
    }

    // Выводим столбцы справа налево, внутри каждого — сверху вниз:
    // так получается поворот прямоугольника на 90 градусов против часовой.
    for (int j = m - 1; j >= 0; --j)
    {
        for (int i = 0; i < n; ++i)
        {
            std::cout << arr[i][j];
        }

        std::cout << '\n';
    }

    return 0;
}
